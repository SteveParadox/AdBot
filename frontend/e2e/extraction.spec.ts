import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('configure schema, extract a dynamic catalog, inspect history and download CSV', async ({page,request})=>{
 const headers={Authorization:'Bearer e2e-local-key-000000000000000000000000'};
 const siteResponse=await request.post('/api/websites',{headers,data:{name:'Extraction E2E',base_url:'http://127.0.0.1:8765/extraction/catalog?dynamic=true',allowed_domains:['127.0.0.1'],authorized:true,configuration:{max_pages:4,max_depth:2,discover_links:false,delay_seconds:.1,max_duration_seconds:60}}});
 expect(siteResponse.ok()).toBeTruthy();
 const site=await siteResponse.json();
 await page.goto('/');
 await page.getByLabel('Workspace API key').fill('e2e-local-key-000000000000000000000000');
 await page.getByRole('button',{name:'Connect workspace'}).click();
 await page.getByRole('button',{name:'Data Extraction',exact:true}).click();
 await page.getByLabel('Built-in template').selectOption('products');
 const definition={name:'Catalog CSS',record_selector:'.product',identity_fields:['product_url'],fields:{name:{type:'string',method:'css',selector:'.name',required:true},price:{type:'currency',method:'css',selector:'.price'},product_url:{type:'url',method:'css',selector:'.product-url',attribute:'href',required:true}}};
 await page.getByLabel('Schema JSON (selectors, identity fields, normalization)').fill(JSON.stringify(definition));
 await page.getByRole('button',{name:'Validate schema',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('Schema is valid');
 await page.getByRole('button',{name:'Create schema',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('Schema created');
 await page.getByText('Create dataset',{exact:true}).click();
 await page.getByLabel('Dataset name').fill('Catalog dataset');
 await page.getByRole('combobox',{name:'Authorized website',exact:true}).selectOption(site.id);
 await page.getByLabel('Dataset options JSON').fill(JSON.stringify({ready_selector:'.product',pagination_selector:'a.next'}));
 await page.getByRole('button',{name:'Save dataset',exact:true}).click();
 await expect(page.getByRole('button',{name:'Run extraction',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Run extraction',exact:true}).click();
 await expect(page.getByText('Orion Workstation',{exact:true}).first()).toBeVisible({timeout:45000});
 await page.getByRole('button',{name:'Inspect history',exact:true}).first().click();
 await expect(page.getByText('Inspection',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'exports',exact:true}).click();
 await page.getByLabel('Export format').selectOption('csv');
 const selection={sort:[{field:'price',direction:'asc'}],limit:1};
 await page.getByLabel('Export filters, sort and limit (JSON)').fill(JSON.stringify(selection));
 await page.getByRole('button',{name:'Queue export',exact:true}).click();
 const downloadButton=page.getByRole('button',{name:'Download',exact:true}).first();
 await expect(downloadButton).toBeEnabled({timeout:30000});
 const downloadEvent=page.waitForEvent('download');
 await downloadButton.click();
 const download=await downloadEvent;
 expect(download.suggestedFilename()).toMatch(/dataset-.*\.csv/);
 const csv=await readFile((await download.path())!, 'utf8');
 expect(csv).toContain('Orion Workstation');
 expect(csv).toContain('12.30');
 // Inspect the same persisted dataset through the API and compare both real
 // downloaded artifacts with its records, rather than trusting a filename.
 const datasets=await (await request.get('/api/extraction/datasets',{headers})).json();
 const dataset=datasets.items.find((d:{name:string})=>d.name==='Catalog dataset');
 const records=await (await request.get(`/api/extraction/datasets/${dataset.id}/records`,{headers})).json();
 expect(records.total).toBe(1);
 expect(csv).toContain(records.items[0].data.product_url);
 await page.getByLabel('Export format').selectOption('json');
 await page.getByRole('button',{name:'Queue export',exact:true}).click();
 const jsonButton=page.getByRole('listitem').filter({hasText:/^json /}).getByRole('button',{name:'Download',exact:true});
 await expect(jsonButton).toBeEnabled({timeout:30000});
 const jsonEvent=page.waitForEvent('download');
 await jsonButton.click();
 const jsonDownload=await jsonEvent;
 expect(jsonDownload.suggestedFilename()).toMatch(/\.json$/);
 const artifact=JSON.parse(await readFile((await jsonDownload.path())!,'utf8'));
 expect(artifact.query).toEqual(expect.objectContaining(selection));
 expect(artifact.records.map((r:{data:unknown})=>r.data)).toEqual(records.items.map((r:{data:unknown})=>r.data));
});
